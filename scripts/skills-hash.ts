// node scripts/skills-hash.ts [--check]: writes src/skills-hash.ts, the hash of the plugin skills the deployed Worker reports from ping.
// Run on deploy. --check only compares (exit 1 on drift); test/skills-hash.test.ts does the same inside `npm run check`.
import { readFileSync, writeFileSync } from "node:fs";
import { pluginFiles, skillsHash } from "../cli/init-core.ts";

const plugin = new URL("../plugin/lite-prototyping/", import.meta.url).pathname;
const out = new URL("../src/skills-hash.ts", import.meta.url).pathname;
const text = `// Generated by scripts/skills-hash.ts from plugin/lite-prototyping (skills and commands). Do not edit.\nexport const SKILLS_HASH = "${skillsHash(pluginFiles(plugin))}";\n`;
let current = "";
try {
  current = readFileSync(out, "utf8");
} catch {}
if (process.argv.includes("--check")) {
  if (current !== text) {
    console.error("src/skills-hash.ts is out of date: run node scripts/skills-hash.ts");
    process.exit(1);
  }
} else if (current !== text) {
  writeFileSync(out, text);
  console.log("wrote src/skills-hash.ts");
}
